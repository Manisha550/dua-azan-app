export function evaluateAuthenticity(d: Partial<Dua>): { isAuthenticFormat: boolean; reason: string } {
  if (!d.source || !d.source.ref) {
    return { isAuthenticFormat: false, reason: 'কোনো প্রামাণ্য রেফারেন্স বা কিতাবের নাম উল্লেখ নেই।' };
  }
  const ref = d.source.ref.toLowerCase();
  const canonicalHadith = ['bukhari', 'muslim', 'tirmidhi', 'abu dawud', 'abu dawood', 'nasai', 'ibn majah', 'ahmad', 'বুখারী', 'বুখারি', 'মুসলিম', 'তিরমিযী', 'তিরমিজি', 'আবু দাউদ'];
  const isHadithCanonical = canonicalHadith.some((c) => ref.includes(c));
  const isQuranCanonical = ref.includes('quran') || ref.includes('কুরআন') || ref.includes('সূরা');

  if (d.source.type === 'quran' && (isQuranCanonical || (d.source.ayahs && d.source.ayahs.length > 0))) {
    return { isAuthenticFormat: true, reason: 'আল-কুরআনের প্রামাণ্য রেফারেন্স শনাক্ত হয়েছে।' };
  }

  if (d.source.type === 'hadith' && isHadithCanonical) {
    return { isAuthenticFormat: true, reason: 'বিশুদ্ধ হাদিস গ্রন্থের (সিহাহ সিত্তা) রেফারেন্স শনাক্ত হয়েছে।' };
  }

  return {
    isAuthenticFormat: false,
    reason: 'উৎসটি সিহাহ সিত্তা বা কুরআনের স্বীকৃত ফরমেটের সাথে আরও যাচাই করা প্রয়োজন (sunnah.com)।',
  };
}

export function loadStoredCustomDuas(): Dua[] {
  try {
    const raw = localStorage.getItem('dua_extra_duas');
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

export function saveStoredCustomDuas(duas: Dua[]) {
  try {
    localStorage.setItem('dua_extra_duas', JSON.stringify(duas));
  } catch (err) {
    console.error('Failed to save custom duas', err);
  }
}

// Verify & Approve a specific Dua (promotes from needs_verification to verified)
export function verifyAndApproveDua(id: string, verifierName: string = 'অ্যাডমিন/যাচাইকারী'): Dua[] {
  const custom = loadStoredCustomDuas();
  const updatedCustom = custom.map((d) => {
    if (d.id === id) {
      return {
        ...d,
        status: 'verified' as const,
        verifiedBy: verifierName,
        verifiedAt: new Date().toLocaleDateString('bn-BD', {
          year: 'numeric',
          month: 'long',
          day: 'numeric',
        }),
        auditNotes: [],
      };
    }
    return d;
  });

  saveStoredCustomDuas(updatedCustom);
  return getAllDuasWithAudit();
}

// Auto-scan and verify eligible duas that have complete fields and authentic citation format
export function autoVerifyEligibleDuas(verifierName: string = 'অটো ভেরিফায়ার'): { count: number; updated: Dua[] } {
  const custom = loadStoredCustomDuas();
  let verifiedCount = 0;

  const updatedCustom = custom.map((d) => {
    if (d.status !== 'verified') {
      const problems = checkSchemaProblems(d);
      const authCheck = evaluateAuthenticity(d);
      if (problems.length === 0 && authCheck.isAuthenticFormat) {
        verifiedCount++;
        return {
          ...d,
          status: 'verified' as const,
          verifiedBy: verifierName,
          verifiedAt: new Date().toLocaleDateString('bn-BD'),
          auditNotes: [],
        };
      }
    }
    return d;
  });

  if (verifiedCount > 0) {
    saveStoredCustomDuas(updatedCustom);
  }

  return { count: verifiedCount, updated: getAllDuasWithAudit() };
}

export function getAllDuasWithAudit(): Dua[] {
  const custom = loadStoredCustomDuas();
  const all = [...BUILTIN_DUAS, ...custom];

  return all.map((d) => {
    const problems = checkSchemaProblems(d);
    const isOk = d.status === 'verified' && problems.length === 0;
    return {
      ...d,
      status: isOk ? 'verified' : 'needs_verification',
      auditNotes: problems,
    };
  });
}

export function getVerifiedDuas(): Dua[] {
  return getAllDuasWithAudit().filter((d) => d.status === 'verified');
}
