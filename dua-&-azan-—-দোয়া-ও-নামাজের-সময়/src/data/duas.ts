// Audit & validation adhering to the user's strict rules
const REQUIRED_FIELDS: (keyof Dua)[] = ['arabic', 'bengali', 'context', 'repetition'];

export function checkSchemaProblems(d: Partial<Dua>): string[] {
  const problems: string[] = [];
  for (const field of REQUIRED_FIELDS) {
    const val = d[field];
    if (typeof val !== 'string' || !val.trim()) {
      problems.push(`অনুপস্থিত বা অপূর্ণ ক্ষেত্র: ${field}`);
    }
  }
  if (!d.source || !d.source.type || !d.source.ref?.trim()) {
    problems.push('রেফারেন্স/উৎস (source) অনুপস্থিত');
  }
  if (d.source && d.source.type === 'quran') {
    if (!Array.isArray(d.source.ayahs) || d.source.ayahs.length === 0) {
      problems.push('কুরআনের দোয়ার জন্য সূরা:আয়াত নম্বর (source.ayahs) আবশ্যক');
    }
  }
  return problems;
}

